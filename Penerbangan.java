package APS1;
class Penerbangan {
    int id;
    String asal;
    String tujuan;
    String tanggal;
    int jam;
    String maskapai;
    int harga;

    Penerbangan(int id, String asal, String tujuan, String tanggal, int jam, String maskapai, int harga) {
        this.id = id;
        this.asal = asal;
        this.tujuan = tujuan;
        this.tanggal = tanggal;
        this.jam = jam;
        this.maskapai = maskapai;
        this.harga = harga;
    }
}
